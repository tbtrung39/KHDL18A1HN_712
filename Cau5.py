# Cau 5.
# Toán tử gán
# a)	Khai báo biến a = 10 và sử dụng += để tăng giá trị lên 5.
# b)	Sử dụng *= để nhân giá trị của a lên 2.
# c)	Sử dụng -= để giảm giá trị của a xuống 3.

# a.
a = 10
a += 5
print("Giá trị của a sau khi tăng 5:", a)

# b.
a *= 2
print("Giá trị của a sau khi nhân với 2:", a)

# c.
a -= 3
print("Giá trị của a sau khi giảm 3:", a)
