# Câu 8.
# Phép toán trên số nguyên
# a)	Nhập một số nguyên và thực hiện phép chia lấy phần nguyên với 7.
# b)	Nhập một số nguyên và thực hiện phép chia lấy dư với 5.

# a.
số = int(input("Nhập một số nguyên: "))
kết_quả = số // 7
print("Kết quả chia lấy phần nguyên với 7 là:", kết_quả)


# b.
số = int(input("Nhập một số nguyên: "))
kết_quả = số % 5
print("Kết quả chia lấy dư với 5 là:", kết_quả)

