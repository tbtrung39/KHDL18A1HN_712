thu = int(input("Nhập thứ trong tuần(2--> 7) : "))
if thu == 2 : 
    print("Monday")
elif thu == 3 : 
    print("Tuesday")
elif thu == 4 : 
    print("Wednesday")
elif thu == 5 : 
    print("Thursday")
elif thu == 6 : 
    print("Saturday")
elif thu == 7 : 
    print("Sunday")
else : 
    print("Nhập sai vui lòng nhập lại") 
