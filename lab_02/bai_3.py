def ten_thu_trong_tuan(thu):
    if thu == 1:
        return "Chủ nhật"
    elif thu == 2:
        return "Thứ hai"
    elif thu == 3:
        return "Thứ ba"
    elif thu == 4:
        return "Thứ tư"
    elif thu == 5:
        return "Thứ năm"
    elif thu == 6:
        return "Thứ sáu"
    elif thu == 7:
        return "Thứ bảy"
    else:
        return "Thứ không hợp lệ"