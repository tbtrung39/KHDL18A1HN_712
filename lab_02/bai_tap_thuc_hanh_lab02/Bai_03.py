thu = int(input("Nhập thứ trong tuần: "))

if thu == 2:
    print("Thứ", thu, "là Monday")
elif thu == 3:
    print("Thứ", thu, "là Tuesday")
elif thu == 4:
    print("Thứ", thu, "là Wednesday")
elif thu == 5:
    print("Thứ", thu, "là Thursday")
elif thu == 6:
    print("Thứ", thu, "là Friday")
elif thu == 7:
    print("Thứ", thu, "là Saturday")
elif thu == 8:
    print("Chủ nhật là Sunday")
else:
    print("Thứ bạn nhập không hợp lệ, vui lòng nhập lại (2-8)")
